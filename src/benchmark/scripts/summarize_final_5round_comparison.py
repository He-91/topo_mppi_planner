#!/usr/bin/env python3
"""Summarize final 5-round Topo-MPPI vs EGO benchmark results.

The script reads the benchmark CSVs generated by run_one_experiment.sh and
prints a compact Markdown table for a benchmark tag, for example:

  python3 src/benchmark/scripts/summarize_final_5round_comparison.py final5_20260626_120000
"""

import argparse
import csv
import math
import re
from collections import defaultdict
from pathlib import Path


def mean(values):
    return sum(values) / len(values) if values else float("nan")


def stdev(values):
    if len(values) < 2:
        return 0.0 if values else float("nan")
    m = mean(values)
    return math.sqrt(sum((v - m) ** 2 for v in values) / (len(values) - 1))


def fmt(value, digits=2):
    if value is None or not math.isfinite(value):
        return "NA"
    return f"{value:.{digits}f}"


def parse_method(name):
    if name.startswith("topo_mppi_"):
        return "Topo-MPPI"
    if name.startswith("ego_"):
        return "EGO"
    return "unknown"


def parse_env(name):
    for env in ("env1", "env2", "env3", "env4", "env5"):
        if env in name:
            return env
    return "unknown"


def load_extended(path, tag):
    rows = []
    if not path.exists():
        return rows
    with path.open(newline="", errors="replace") as f:
        reader = csv.DictReader(f)
        for row in reader:
            exp_name = row.get("exp_name") or row.get("name") or ""
            # Final benchmark snapshots do not contain exp_name because
            # benchmark_node records method/scenario/run_id only. In that case
            # the snapshot file itself is the filter.
            if exp_name and tag not in exp_name:
                continue
            row["_method"] = parse_method(exp_name) if exp_name else row.get("method", "unknown")
            if row["_method"] == "topo_mppi":
                row["_method"] = "Topo-MPPI"
            elif row["_method"] == "ego":
                row["_method"] = "EGO"
            row["_env"] = parse_env(exp_name) if exp_name else row.get("scenario", "unknown")
            rows.append(row)
    return rows


def as_float(row, keys):
    for key in keys:
        if key in row and row[key] not in ("", "nan", "NA"):
            try:
                return float(row[key])
            except ValueError:
                pass
    return float("nan")


def as_int(row, keys):
    value = as_float(row, keys)
    if math.isfinite(value):
        return int(round(value))
    return 0


def load_legacy_tail(path):
    """Read run_one_experiment.sh text results for log-only diagnostics.

    benchmark_results_extended.csv intentionally contains executed-trajectory
    metrics, but it does not carry planner log counters such as ColWarn,
    TopoFail, or BsplineFail. The final batch writes a matching text tail, so
    we join by method/env/run order.
    """
    rows = {}
    if not path.exists():
        return rows

    pattern = re.compile(
        r"^(?P<name>\S+) \| (?P<status>\S+) \| (?P<wall>\d+)s .*?"
        r"goal_dist=(?P<goal>[0-9.]+) \| replans=(?P<replans>\d+) "
        r"\| col=(?P<col>\d+) \| topo_fail=(?P<topo>\d+) "
        r"\| bs_fail=(?P<bs>\d+)"
    )
    for line in path.read_text(errors="replace").splitlines():
        match = pattern.search(line)
        if not match:
            continue
        name = match.group("name")
        method = parse_method(name)
        env = parse_env(name)
        run_match = re.search(r"_r(\d+)$", name)
        if method == "unknown" or env == "unknown" or not run_match:
            continue
        rows[(env, method, int(run_match.group(1)))] = {
            "legacy_status": match.group("status"),
            "legacy_wall_time_s": float(match.group("wall")),
            "legacy_goal_dist_m": float(match.group("goal")),
            "legacy_replans": float(match.group("replans")),
            "legacy_colwarn": float(match.group("col")),
            "legacy_topo_fail": float(match.group("topo")),
            "legacy_bspline_fail": float(match.group("bs")),
        }
    return rows


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("tag", help="Benchmark tag, e.g. final5_20260626_120000")
    parser.add_argument(
        "--results-dir",
        default="src/benchmark/results",
        help="Directory containing benchmark_results_extended.csv",
    )
    parser.add_argument(
        "--extended-csv",
        default="",
        help="Use this filtered extended metrics CSV instead of the master file",
    )
    parser.add_argument(
        "--results-tail",
        default="",
        help="Use this final results_master tail to add ColWarn/Replans/TopoFail/BsplineFail",
    )
    args = parser.parse_args()

    result_dir = Path(args.results_dir)
    extended_path = Path(args.extended_csv) if args.extended_csv else result_dir / f"{args.tag}_benchmark_results_extended.csv"
    if not extended_path.exists() and not args.extended_csv:
        extended_path = result_dir / "benchmark_results_extended.csv"
    rows = load_extended(extended_path, args.tag)
    if not rows:
        raise SystemExit(f"No extended benchmark rows found for tag: {args.tag}")

    tail_path = Path(args.results_tail) if args.results_tail else result_dir / f"{args.tag}_results_master_tail.txt"
    legacy = load_legacy_tail(tail_path)
    order = defaultdict(int)
    for row in rows:
        key = (row["_env"], row["_method"])
        order[key] += 1
        row.update(legacy.get((row["_env"], row["_method"], order[key]), {}))

    groups = defaultdict(list)
    for row in rows:
        groups[(row["_env"], row["_method"])].append(row)

    print(f"# Final 5-Round Benchmark Summary: `{args.tag}`")
    print()
    print("| Env | Method | Runs | Success | Time mean +/- std (s) | Path mean (m) | Static clearance mean (m) | Static collision mean | Dynamic collision mean | ColWarn mean | Replans mean | TopoFail mean | BsFail mean |")
    print("| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |")

    for env in ("env1", "env2", "env3", "env4", "env5"):
        for method in ("Topo-MPPI", "EGO"):
            group = groups.get((env, method), [])
            if not group:
                print(f"| {env} | {method} | 0 | 0/0 | NA | NA | NA | NA | NA | NA | NA | NA | NA |")
                continue
            successes = [
                as_int(row, ["success", "is_success"]) for row in group
            ]
            successful_rows = [row for row, ok in zip(group, successes) if ok == 1]
            metric_rows = successful_rows or group
            times = [as_float(row, ["completion_time_s", "time_s", "total_time_s", "travel_time_s"]) for row in metric_rows]
            paths = [as_float(row, ["path_length_m", "traj_length_m"]) for row in metric_rows]
            clearances = [as_float(row, ["min_static_clearance_m", "min_obs_dist_m", "min_clearance_m"]) for row in metric_rows]
            collisions = [as_float(row, ["static_collision_count", "collision_count"]) for row in metric_rows]
            dynamic_collisions = [as_float(row, ["dynamic_collision_count"]) for row in metric_rows]
            # Log counters are attached to all rows, including failed runs,
            # because they diagnose why a batch lost robustness.
            colwarns = [as_float(row, ["legacy_colwarn", "col_warn", "collision_warn", "colwarn"]) for row in group]
            replans = [as_float(row, ["legacy_replans"]) for row in group]
            topo_fails = [as_float(row, ["legacy_topo_fail"]) for row in group]
            bspline_fails = [as_float(row, ["legacy_bspline_fail"]) for row in group]

            times = [v for v in times if math.isfinite(v)]
            paths = [v for v in paths if math.isfinite(v)]
            clearances = [v for v in clearances if math.isfinite(v)]
            collisions = [v for v in collisions if math.isfinite(v)]
            dynamic_collisions = [v for v in dynamic_collisions if math.isfinite(v)]
            colwarns = [v for v in colwarns if math.isfinite(v)]
            replans = [v for v in replans if math.isfinite(v)]
            topo_fails = [v for v in topo_fails if math.isfinite(v)]
            bspline_fails = [v for v in bspline_fails if math.isfinite(v)]

            print(
                f"| {env} | {method} | {len(group)} | {sum(successes)}/{len(group)} | "
                f"{fmt(mean(times))} +/- {fmt(stdev(times))} | "
                f"{fmt(mean(paths))} | {fmt(mean(clearances), 3)} | "
                f"{fmt(mean(collisions))} | {fmt(mean(dynamic_collisions))} | "
                f"{fmt(mean(colwarns))} | {fmt(mean(replans))} | "
                f"{fmt(mean(topo_fails))} | {fmt(mean(bspline_fails))} |"
            )


if __name__ == "__main__":
    main()
